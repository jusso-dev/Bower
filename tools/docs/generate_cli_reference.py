"""Generate docs/reference/cli.md from the bower CLI's own help text.

The help text lives in src/Bower.Cli/Commands/CliHelp.cs (what `bower --help` prints).
CliHelpTests in tests/Bower.UnitTests fails when the page and the help differ, so the
reference cannot go stale. Standard library only.

    python3 -I tools/docs/generate_cli_reference.py          # write
    python3 -I tools/docs/generate_cli_reference.py --check  # fail if stale
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src/Bower.Cli/Commands/CliHelp.cs"
TARGET = ROOT / "docs/reference/cli.md"

# Where each command group is explained. Keys are the first word after `bower`.
GUIDES = {
    "validate": ("Policies", "../deployment/packs.md"),
    "pipeline": ("Pipelines", "../architecture/overview.md"),
    "queue": ("Queue durability", "../operations/queue-v5-durability.md"),
    "test": ("Fleet and queue integrity", "../operations/fleet-and-queue-integrity.md"),
    "token": ("Fleet and queue integrity", "../operations/fleet-and-queue-integrity.md"),
    "doctor": ("Doctor and DCR checks", "../operations/doctor-and-dcr.md"),
    "dcr": ("Doctor and DCR checks", "../operations/doctor-and-dcr.md"),
    "keys": ("Signed packs", "../deployment/packs.md"),
    "pack": ("Signed packs", "../deployment/packs.md"),
    "evidence": ("Evidence bundles", "../operations/evidence-bundles.md"),
    "developer": ("ASP.NET Core", "../developer-integration/aspnetcore.md"),
    "privacy": ("Custom redaction rules", "../privacy/custom-redaction-rules.md"),
    "policy": ("Suppression, population diff and archive", "../operations/suppression-archive-and-source-silence.md"),
    "archive": ("Suppression, population diff and archive", "../operations/suppression-archive-and-source-silence.md"),
    "sources": ("Source silence", "../operations/suppression-archive-and-source-silence.md"),
    "tap": ("Tap and top", "../operations/tap-and-top.md"),
    "top": ("Tap and top", "../operations/tap-and-top.md"),
    "version": ("Release versioning", "../operations/release-versioning.md"),
    "wec": ("Windows Event Forwarding", "../deployment/windows-event-forwarding.md"),
}


def help_text() -> str:
    source = SOURCE.read_text(encoding="utf-8")
    match = re.search(r'"""\n(.*?)\n\s*""";', source, re.S)
    if not match:
        raise SystemExit(f"No raw string literal in {SOURCE}")
    lines = match.group(1).split("\n")
    indent = min(len(line) - len(line.lstrip()) for line in lines if line.strip())
    return "\n".join(line[indent:] for line in lines)


def commands(text: str) -> list[str]:
    seen: list[str] = []
    for line in text.split("\n"):
        found = re.match(r"\s+bower ([a-z-]+)", line)
        if found and found.group(1) not in seen:
            seen.append(found.group(1))
    return seen


def render() -> str:
    text = help_text()
    rows = []
    for command in commands(text):
        title, link = GUIDES.get(command, (None, None))
        if title is None:
            raise SystemExit(f"No guide for `bower {command}`: add it to GUIDES in {Path(__file__).name}.")
        rows.append(f"| `bower {command}` | [{title}]({link}) |")
    lines = [
        "# bower CLI reference",
        "",
        "<!-- Generated by tools/docs/generate_cli_reference.py from src/Bower.Cli/Commands/CliHelp.cs. Do not edit. -->",
        "",
        "This is exactly what `bower --help` prints for this release. Every `--option` takes",
        "the next argument as its value, the first occurrence wins, and unknown options are",
        "ignored together with their value. Commands exit 0 on success and 1 on failure;",
        "`pipeline validate` exits 2 when the document is invalid.",
        "",
        "```text",
        text,
        "```",
        "",
        "## Where each command is explained",
        "",
        "| Command | Guide |",
        "|---|---|",
        *rows,
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != expected:
            raise SystemExit("CLI reference is stale. Run python3 -I tools/docs/generate_cli_reference.py and commit the result.")
    else:
        TARGET.write_text(expected, encoding="utf-8")
