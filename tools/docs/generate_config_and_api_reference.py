"""Generate docs/reference/configuration.md and docs/reference/api.md from repo sources.

Reads JSON schemas under schemas/, collector environment variables in
src/Bower.Collector/CollectorSettings.cs, and HTTP routes in
src/Bower.Collector/CollectorApplication.cs and src/Bower.Management.Api/*.cs.
Standard library only.

    python3 -I tools/docs/generate_config_and_api_reference.py          # write
    python3 -I tools/docs/generate_config_and_api_reference.py --check  # fail if stale
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMAS_DIR = ROOT / "schemas"
COLLECTOR_SETTINGS = ROOT / "src/Bower.Collector/CollectorSettings.cs"
COLLECTOR_APP = ROOT / "src/Bower.Collector/CollectorApplication.cs"
MANAGEMENT_DIR = ROOT / "src/Bower.Management.Api"
CONFIG_TARGET = ROOT / "docs/reference/configuration.md"
API_TARGET = ROOT / "docs/reference/api.md"

ENV_PATTERN = re.compile(r"\b(BOWER_[A-Z0-9_]+)\b")
ROUTE_PATTERN = re.compile(
    r'\b(app|api|relay|group)\.Map(Get|Post|Put|Delete|Patch)\(\s*"([^"]+)"',
    re.S,
)


def _clean(text: str) -> str:
    return re.sub(r"\s+", " ", text or "").strip().replace("|", "\\|")


def render_configuration() -> str:
    schema_files = sorted(SCHEMAS_DIR.rglob("*.json"))
    schema_rows: list[str] = []
    schema_sections: list[str] = []

    for path in schema_files:
        rel = path.relative_to(ROOT).as_posix()
        data = json.loads(path.read_text(encoding="utf-8"))
        title = _clean(data.get("title") or path.stem)
        desc = _clean(data.get("description") or "")
        required = data.get("required") or []
        props = data.get("properties") or {}
        schema_rows.append(f"| `{rel}` | {title} | {len(props)} |")

        schema_sections.append(f"### `{rel}`")
        schema_sections.append("")
        if desc:
            schema_sections.append(desc)
            schema_sections.append("")
        if required:
            req_list = ", ".join(f"`{r}`" for r in required)
            schema_sections.append(f"Required fields: {req_list}.")
            schema_sections.append("")
        if props:
            schema_sections.append("| Property | Type | Required | Description |")
            schema_sections.append("|---|---|---|---|")
            for prop_name, prop_def in props.items():
                if not isinstance(prop_def, dict):
                    continue
                ptype = prop_def.get("type", "object")
                if isinstance(ptype, list):
                    ptype = " \\| ".join(str(t) for t in ptype)
                is_req = "Yes" if prop_name in required else "No"
                pdesc = _clean(prop_def.get("description") or "")
                schema_sections.append(f"| `{prop_name}` | `{ptype}` | {is_req} | {pdesc} |")
            schema_sections.append("")

    settings_text = COLLECTOR_SETTINGS.read_text(encoding="utf-8")
    env_vars = sorted(
        {m.group(1) for m in ENV_PATTERN.finditer(settings_text) if not m.group(1).endswith("_")}
    )

    lines = [
        "# Configuration and schema reference",
        "",
        "<!-- Generated by tools/docs/generate_config_and_api_reference.py. Do not edit. -->",
        "",
        "This page is generated directly from `schemas/` and `src/Bower.Collector/CollectorSettings.cs`.",
        "CI runs `generate_config_and_api_reference.py --check` so the reference cannot drift from the code.",
        "",
        "## Collector environment variables",
        "",
        f"Recognised collector settings (`{len(env_vars)}` variables in `CollectorSettings.cs`):",
        "",
        "| Environment variable |",
        "|---|",
        *(f"| `{var}` |" for var in env_vars),
        "",
        "## Versioned JSON schemas",
        "",
        "| Schema file | Title | Top-level properties |",
        "|---|---|---|",
        *schema_rows,
        "",
        *schema_sections,
    ]
    return "\n".join(lines).rstrip() + "\n"


def _extract_routes(file_path: Path, default_prefix: str) -> list[tuple[str, str, str]]:
    text = file_path.read_text(encoding="utf-8")
    routes: list[tuple[str, str, str]] = []
    for match in ROUTE_PATTERN.finditer(text):
        receiver = match.group(1)
        method = match.group(2).upper()
        raw_path = match.group(3)
        if receiver == "api" and not raw_path.startswith("/api"):
            full_path = f"{default_prefix}{raw_path}"
        else:
            full_path = raw_path
        # Look ahead briefly for RequireAuthorization("Role")
        tail = text[match.end():match.end() + 900]
        auth_match = re.search(r'RequireAuthorization\("([^"]+)"\)', tail)
        allow_anon = "AllowAnonymous()" in tail[:300]
        if allow_anon:
            access = "Anonymous"
        elif auth_match:
            access = f"Role: `{auth_match.group(1)}`"
        elif "IngestAuthenticationFilter" in tail[:500]:
            access = "Ingest bearer token"
        else:
            access = "Host policy"
        routes.append((method, full_path, access))
    return routes


def render_api() -> str:
    collector_routes = sorted(set(_extract_routes(COLLECTOR_APP, "")))
    management_routes_set: set[tuple[str, str, str]] = set()
    for cs_file in sorted(MANAGEMENT_DIR.glob("*.cs")):
        for route in _extract_routes(cs_file, "/api"):
            management_routes_set.add(route)
    management_routes = sorted(management_routes_set, key=lambda r: (r[1], r[0]))

    lines = [
        "# Collector and Management HTTP API reference",
        "",
        "<!-- Generated by tools/docs/generate_config_and_api_reference.py. Do not edit. -->",
        "",
        "This page is generated directly from the route registrations in",
        "`src/Bower.Collector/CollectorApplication.cs` and `src/Bower.Management.Api/*.cs`.",
        "All endpoints return metadata or post-redaction views only; management storage never holds raw event payloads.",
        "",
        "## Collector HTTP endpoints",
        "",
        "| Method | Path | Access |",
        "|---|---|---|",
        *(f"| `{m}` | `{p}` | {a} |" for m, p, a in collector_routes),
        "",
        "## Management API endpoints",
        "",
        "Authenticated via Microsoft Entra ID (`Bower.Viewer`, `Bower.Operator`, `Bower.Approver`, `Bower.Collector`) or enrolled collector key assertions.",
        "",
        "| Method | Path | Access |",
        "|---|---|---|",
        *(f"| `{m}` | `{p}` | {a} |" for m, p, a in management_routes),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    outputs = [
        (CONFIG_TARGET, render_configuration()),
        (API_TARGET, render_api()),
    ]
    if args.check:
        stale = [
            target.relative_to(ROOT).as_posix()
            for target, expected in outputs
            if not target.exists() or target.read_text(encoding="utf-8") != expected
        ]
        if stale:
            raise SystemExit(
                f"Generated reference is stale ({', '.join(stale)}). "
                "Run python3 -I tools/docs/generate_config_and_api_reference.py and commit the result."
            )
    else:
        for target, content in outputs:
            target.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
