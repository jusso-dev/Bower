//! Cross-implementation vectors produced by `Bower.Integrity` (C#, .NET 10).
//!
//! `fixtures/csharp-vectors.json` was written by a temporary xunit test against the
//! C# HEAD: canonical JSON of tricky inputs, a C#-generated P-256 key (PKCS#8, SEC1
//! and SPKI PEM), C# signatures, and C#'s verdicts on a Rust-generated key and
//! signature (`RUST_*` below). Together they prove both directions: Rust verifies
//! C# signatures and C# verifies Rust signatures.

use std::path::PathBuf;

use bower_integrity::{
    DetachedSignature, ECDSA_P256_SHA256, IntegrityError, canonical_json,
    key_id_from_public_key_pem, sign, verify,
};
use serde_json::Value;

