const RUST_PUBLIC: &str = "-----BEGIN PUBLIC KEY-----\nMFkwEwYHKoZIzj0CAQYIKoZIzj0DAQcDQgAEae6xHbQOKD5N36VjA96vPrhZN93v\n07peej5QeFlas/CDsXO6ACpitVGGRhMZBSfFLxqWWZQugFIf6a9X7Q+/tg==\n-----END PUBLIC KEY-----";
/// Rust signature over `bower evidence` with `RUST_PRIVATE`; C# verified it.
const RUST_SIGNATURE: &str =
    "+i98QtDS3MXr2jlzuGqHFsBVz45oLdYto9eeheVvzRoZ2SxXvuTAg4IBlngbtaetbV1cXGm+IVIIbOHgJxNuRQ==";
/// Half the P-256 group order: `s` above it is "high-S".
const HALF_ORDER: [u8; 32] = [
    0x7F, 0xFF, 0xFF, 0xFF, 0x80, 0x00, 0x00, 0x00, 0x7F, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xDE, 0x73, 0x7D, 0x56, 0xD3, 0x8B, 0xCF, 0x42, 0x79, 0xDC, 0xE5, 0x61, 0x7E, 0x31, 0x92, 0xA8,
];

fn vectors() -> Value {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/csharp-vectors.json");
    serde_json::from_slice(&std::fs::read(path).unwrap()).unwrap()
}

fn text<'a>(value: &'a Value, name: &str) -> &'a str {
    value[name]
        .as_str()
        .unwrap_or_else(|| panic!("{name} missing"))
}

fn signature(key_id: &str, value: &str) -> DetachedSignature {
    DetachedSignature {
        algorithm: ECDSA_P256_SHA256.to_owned(),
        key_id: key_id.to_owned(),
        value: value.to_owned(),
    }
}

#[test]
fn canonical_json_matches_csharp_bytes() {
    let vectors = vectors();
    let cases = vectors["canonical"].as_array().unwrap();
    assert!(cases.len() >= 7);
    for case in cases {
        let input = text(case, "input");
        let expected = text(case, "canonical");
        assert_eq!(
            canonical_json::bytes_from_str(input).unwrap(),
            expected.as_bytes(),
            "input {input}"
        );
        // The `Value` path is identical except for exponent spelling, which
        // serde_json normalises (`1E2` -> `1e+2`) and C# keeps.
        let value: Value = serde_json::from_str(input).unwrap();
        let has_exponent = input.contains("1.0E+2");
        assert_eq!(
            canonical_json::text(&value) == expected,
            !has_exponent,
            "input {input}"
        );
    }
}

#[test]
fn canonical_rejects_duplicate_properties_like_csharp_json_object() {
    assert!(canonical_json::bytes_from_str(r#"{"a":1,"a":2}"#).is_err());
    assert!(canonical_json::bytes_from_str(r#"{"o":{"a":1,"a":2}}"#).is_err());
    assert_eq!(
        canonical_json::compact_from_str(r#"{ "b" : {"x":1,"x":2}, "a" : 1E2 }"#).unwrap(),
        br#"{"b":{"x":1,"x":2},"a":1E2}"#
    );
}

#[test]
fn csharp_key_formats_import_with_the_same_key_id() {
    let vectors = vectors();
    let signing = &vectors["signing"];
    let key_id = text(signing, "keyId");
    for pem in ["spki", "pkcs8", "sec1"] {
        assert_eq!(
            key_id_from_public_key_pem(text(signing, pem)).unwrap(),
            key_id,
            "{pem}"
        );
    }
    assert_eq!(text(signing, "keyIdFromPrivate"), key_id);
    assert_eq!(text(signing, "keyIdFromSec1"), key_id);
}

#[test]
fn rust_verifies_csharp_p1363_signatures_including_high_s() {
    let vectors = vectors();
    let signing = &vectors["signing"];
    let message = text(signing, "message").as_bytes();
    let key_id = text(signing, "keyId");
    let spki = text(signing, "spki");
    let mut high_s = 0;
    for value in signing["signatures"].as_array().unwrap() {
        let value = value.as_str().unwrap();
        let raw = base64_decode(value);
        assert_eq!(raw.len(), 64, "C# writes IEEE P1363 r||s, not DER");
        if raw[32..] > HALF_ORDER[..] {
            high_s += 1;
        }
        let parsed = signature(key_id, value);
        assert!(verify(message, &parsed, [spki]));
        // A private key PEM is accepted as a trusted key, as in C#.
        assert!(verify(message, &parsed, [text(signing, "pkcs8")]));
        assert!(!verify(b"bower evidencf", &parsed, [spki]));
    }
    assert!(high_s > 0, "C# emits unnormalised s; Rust must accept it");

    let canonical: Value = serde_json::from_str(text(&vectors["canonical"][0], "input")).unwrap();
    assert!(verify(
        &canonical_json::bytes(&canonical),
        &signature(key_id, text(signing, "canonicalSignature")),
        [spki]
    ));
}

#[test]
fn csharp_verifies_rust_signatures() {
    let vectors = vectors();
    let signing = &vectors["signing"];
    let rust_key_id = key_id_from_public_key_pem(RUST_PUBLIC).unwrap();
    assert_eq!(text(signing, "rustKeyId"), rust_key_id);
    assert_eq!(text(signing, "rustKeyIdFromPrivate"), rust_key_id);
    assert_eq!(signing["rustSignatureVerifies"], true);
    assert_eq!(signing["rustSignatureVerifiesCrlf"], true);
    assert_eq!(signing["rustSignatureVerifiesWithPrivatePem"], true);
    assert_eq!(signing["rustSignatureTamperedVerifies"], false);

    // The Rust signature C# accepted is what Rust produces (and verifies) here.
    let message = text(signing, "message").as_bytes();
    let ours = signature(&rust_key_id, RUST_SIGNATURE);
    assert!(verify(message, &ours, [RUST_PUBLIC]));
    assert!(verify(
        message,
        &ours,
        [RUST_PUBLIC.replace('\n', "\r\n").as_str()]
    ));
    let fresh = sign(message, RUST_PRIVATE).unwrap();
    assert_eq!(fresh.key_id, rust_key_id);
    assert!(verify(message, &fresh, [RUST_PUBLIC]));

    // C# signing with the Rust-generated PKCS#8 key verifies in Rust.
    assert!(verify(
        message,
        &signature(&rust_key_id, text(signing, "signedWithRustKey")),
        [RUST_PUBLIC]
    ));

    // Base64 whitespace handling matches Convert.FromBase64String.
    let spaced = format!("{} \r\n\t{}", &RUST_SIGNATURE[..20], &RUST_SIGNATURE[20..]);
    assert_eq!(
        verify(message, &signature(&rust_key_id, &spaced), [RUST_PUBLIC]),
        signing["rustSignatureWithWhitespaceVerifies"]
            .as_bool()
            .unwrap()
    );
}

#[test]
fn rust_signs_with_csharp_exported_keys() {
    let vectors = vectors();
    let signing = &vectors["signing"];
    let spki = text(signing, "spki");
    for pem in ["pkcs8", "sec1"] {
        let signed = sign(b"cross", text(signing, pem)).unwrap();
        assert_eq!(signed.key_id, text(signing, "keyId"));
        assert_eq!(base64_decode(&signed.value).len(), 64);
        assert!(verify(b"cross", &signed, [spki]), "{pem}");
    }
}

#[test]
fn p384_keys_are_rejected_like_csharp() {
    let vectors = vectors();
    let signing = &vectors["signing"];
    assert_eq!(text(signing, "p384Sign"), "throws:CryptographicException");
    assert_eq!(
        sign(b"x", text(signing, "p384Private")).unwrap_err(),
        IntegrityError::NotP256
    );
    assert!(key_id_from_public_key_pem(text(signing, "p384Public")).is_err());
    let any = signature(text(signing, "keyId"), text(signing, "canonicalSignature"));
    assert!(!verify(b"x", &any, [text(signing, "p384Public")]));
}

#[test]
fn signature_json_matches_csharp_serializer() {
    let vectors = vectors();
    let json = text(&vectors["signing"], "signatureJson");
    let parsed: DetachedSignature = serde_json::from_str(json).unwrap();
    assert_eq!(parsed.value, RUST_SIGNATURE);
    assert_eq!(bower_contracts::json::to_string(&parsed).unwrap(), json);
}

fn base64_decode(value: &str) -> Vec<u8> {
    use base64::Engine;
    base64::engine::general_purpose::STANDARD
        .decode(value)
        .unwrap()
}
