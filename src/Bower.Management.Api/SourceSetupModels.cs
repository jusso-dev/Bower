using Bower.Integrity;

namespace Bower.Management.Api;

/// <summary>Input kinds the console's one generic source form knows how to render.</summary>
public static class SourceFieldKinds
{
    public const string Text = "text";
    public const string Number = "number";
    public const string Choice = "choice";
    public const string Boolean = "boolean";
    /// <summary>IP addresses or CIDR ranges, one per line or comma-separated.</summary>
    public const string AddressList = "address-list";
    /// <summary>Comma-separated names (for example S3 buckets).</summary>
    public const string NameList = "name-list";
    /// <summary>An absolute path on the host that runs the component.</summary>
    public const string FilePath = "file-path";
    /// <summary>Where a secret lives (file path or Key Vault secret URL), never the secret itself.</summary>
    public const string SecretReference = "secret-reference";
    public const string Url = "url";
}

public sealed record SourceFieldOption(string Value, string Label);

/// <summary>
/// One input of a source type. Kinds, bounds and choices are public so the console can guide;
/// the server re-checks everything, including the server-only text patterns.
/// </summary>
public sealed record SourceFieldDefinition(
    string Id,
    string Label,
    string Kind,
    bool Required,
    string Help,
    string? DefaultValue = null,
    string? Placeholder = null,
    IReadOnlyList<SourceFieldOption>? Options = null,
    int? Minimum = null,
    int? Maximum = null,
    int MaximumLength = 256,
    bool KeyVaultAllowed = false,
    // Shown only when another field has one of these values (for example TLS files).
    string? ShownWhenField = null,
    IReadOnlyList<string>? ShownWhenValues = null);

/// <summary>A guided source type: what it is, what you need and the fields of its form.</summary>
public sealed record SourceTypeDefinition(
    string Id,
    string Title,
    string Summary,
    string Why,
    IReadOnlyList<string> Needs,
    IReadOnlyList<SourceFieldDefinition> Fields,
    string CheckDescription,
    string Guide);

/// <summary>Body of <c>POST /api/sources/plan</c>.</summary>
public sealed record SourceSetupDraft(
    string? Type,
    string? CollectorId,
    Dictionary<string, string>? Values);

/// <summary>Body of <c>POST /api/sources/requests</c>.</summary>
public sealed record SourceSetupSubmission(
    string? Type,
    string? CollectorId,
    Dictionary<string, string>? Values,
    string? Reason);

/// <summary>A generated configuration file and where it is installed.</summary>
public sealed record SourceSetupFile(string Name, string InstallPath, string Description, string Content);

/// <summary>An environment variable for the component the file belongs to.</summary>
public sealed record SourceSetupVariable(string Component, string Name, string Value);

/// <summary>Copy-paste text for the sender or the cloud side (rsyslog, Compose labels, SDK code).</summary>
public sealed record SourceSetupSnippet(string Title, string Description, string Language, string Content);

/// <summary>
/// What the server watches on the collector's heartbeat to prove the source works:
/// <c>source</c> (an expected application, id <c>application/environment</c>) or
/// <c>output</c> (an output report, for example <c>ama-spool</c>).
/// </summary>
public sealed record SourceSetupVerification(string Kind, string ReportId, string Description);

/// <summary>
/// Everything a source setup request installs. Generated by the server from validated values
/// only; <see cref="ContentHash"/> covers type, collector, files, variables, snippets and
/// verification, so an approval approves exactly these bytes.
/// </summary>
public sealed record SourceSetupPlan(
    IReadOnlyList<SourceSetupFile> Files,
    IReadOnlyList<SourceSetupVariable> Variables,
    IReadOnlyList<SourceSetupSnippet> Snippets,
    SourceSetupVerification Verification,
    string ContentHash);

/// <summary>
/// A server-owned synthetic sample event for the source type after redaction. The sample holds
/// no real data and only the redacted form leaves the server.
/// </summary>
public sealed record SourceSetupPreview(
    bool Valid,
    string? Redacted,
    IReadOnlyList<PrivacyProfilePreviewFinding> Findings,
    string Rules);

/// <summary>Result of <c>POST /api/sources/plan</c>: checks, the generated plan and the redacted preview.</summary>
public sealed record SourceSetupPlanResult(
    bool Valid,
    IReadOnlyList<SetupCheck> Checks,
    SourceSetupPlan? Plan,
    SourceSetupPreview? Preview);

public static class SourceSetupRequestStatus
{
    public const string PendingReview = "pending-review";
    public const string Approved = "approved";
    public const string Rejected = "rejected";
}

/// <summary>
/// The server's answer to "is this source working?", worked out at query time from the
/// request state and the collector's last heartbeat. <see cref="State"/> is a guided state
/// (<c>complete</c>, <c>in-progress</c>, <c>attention</c>, <c>blocked</c>) and
/// <see cref="Label"/> fixed Bower words; the console never decides this itself.
/// </summary>
public sealed record SourceSetupStatusCheck(
    string State,
    string Label,
    IReadOnlyList<SetupCheck> Checks,
    DateTimeOffset? LastEventAt,
    DateTimeOffset? CollectorSeenAt,
    DateTimeOffset CheckedAt);

public sealed record SourceSetupRequestSummary(
    string Id,
    string Type,
    string TypeTitle,
    string CollectorId,
    string Status,
    string ContentHash,
    string Reason,
    string RequestedByName,
    DateTimeOffset RequestedAt,
    string? ReviewerName,
    DateTimeOffset? ReviewedAt,
    string? ReviewReason,
    SourceSetupStatusCheck Check);

/// <summary>Summary plus the validated values, the generated plan and the requester's object id (for four-eyes).</summary>
public sealed record SourceSetupRequestDetail(
    string Id,
    string Type,
    string TypeTitle,
    string CollectorId,
    string Status,
    string ContentHash,
    string Reason,
    string RequestedByName,
    DateTimeOffset RequestedAt,
    string? ReviewerName,
    DateTimeOffset? ReviewedAt,
    string? ReviewReason,
    SourceSetupStatusCheck Check,
    string RequestedByObjectId,
    IReadOnlyDictionary<string, string> Values,
    SourceSetupPlan Plan);

/// <summary>
/// The approved configuration as a signed document. The signature is ECDSA P-256 over the
/// canonical JSON of every field except <see cref="Signature"/>; the signed <see cref="Kind"/>
/// keeps it from verifying as any other Bower document.
/// </summary>
public sealed record SignedSourceSetup(
    string Kind,
    string RequestId,
    string CollectorId,
    string SourceType,
    string ContentHash,
    IReadOnlyList<SourceSetupFile> Files,
    IReadOnlyList<SourceSetupVariable> Variables,
    IReadOnlyList<SourceSetupSnippet> Snippets,
    SourceSetupVerification Verification,
    string ApprovedAt,
    DetachedSignature Signature);
