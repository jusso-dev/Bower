using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml;

namespace Bower.Source.WindowsEventLog;

/// <summary>WEF delivery optimisation (<c>ConfigurationMode</c>).</summary>
public enum WecDeliveryMode
{
    /// <summary>Minimise latency: about 30-second batches. The default for security events.</summary>
    MinLatency,

    /// <summary>Windows default: pull-style batching, about 15 minutes.</summary>
    Normal,

    /// <summary>Minimise bandwidth: about 6 hours.</summary>
    MinBandwidth,

    /// <summary>Explicit <c>MaxItems</c> and <c>MaxLatencyTime</c>.</summary>
    Custom
}

/// <summary>
/// Options for one source-initiated Windows Event Forwarding subscription. The event
/// selection comes from a validated <see cref="WindowsEventSubscriptionOptions"/> (channel,
/// event IDs, providers), never from free text, so the forwarders select at source exactly
/// what the collector's subscription accepts.
/// </summary>
/// <param name="SubscriptionId">WEC subscription name. Defaults to <c>bower-</c> plus the Bower subscription id.</param>
/// <param name="IssuerCaThumbprints">Issuing CA thumbprints for certificate-authenticated (workgroup or DMZ) forwarders.</param>
/// <param name="AllowedSourceDomainComputers">SDDL of the domain computers allowed to forward; null uses Domain Computers.</param>
public sealed record WecSubscriptionOptions(
    WecDeliveryMode Mode = WecDeliveryMode.MinLatency,
    int? MaxItems = null,
    int? MaxLatencySeconds = null,
    int HeartbeatSeconds = 900,
    bool ReadExistingEvents = false,
    string? SubscriptionId = null,
    string? AllowedSourceDomainComputers = null,
    IReadOnlyList<string>? IssuerCaThumbprints = null,
    string LogFile = "ForwardedEvents");

/// <summary>
/// Writes WEC subscription XML (<c>wecutil cs FILE</c>) for a Bower Windows Event Log
/// subscription. HTTPS only: the transport is fixed to <c>HTTPS</c>, so forwarders use
/// WinRM on 5986 with Kerberos (domain) or a client certificate (workgroup and DMZ).
/// </summary>
public static partial class WecSubscription
{
    /// <summary>Domain Computers may forward (the Windows default without the local Network Service entry).</summary>
    public const string DefaultDomainComputers = "O:NSG:NSD:(A;;GA;;;DC)";

    public const string Namespace = "http://schemas.microsoft.com/2006/03/windows/events/subscription";

    public static string Generate(WindowsEventSubscriptionOptions subscription, WecSubscriptionOptions options)
    {
        ArgumentNullException.ThrowIfNull(subscription);
        ArgumentNullException.ThrowIfNull(options);
        Validate(options);

        string id = options.SubscriptionId ?? "bower-" + subscription.Id;
        // The query filter forwarders apply at source: the collector's generated XPath with no
        // record position (a forwarder has its own bookmark per subscription).
        string select = WindowsEventQuery.For(subscription, 0).ToXPath(includeRecordPosition: false);
        StringBuilder query = new();
        using (XmlWriter writer = XmlWriter.Create(query, new XmlWriterSettings { OmitXmlDeclaration = true, Indent = false }))
        {
            writer.WriteStartElement("QueryList");
            writer.WriteStartElement("Query");
            writer.WriteAttributeString("Id", "0");
            writer.WriteAttributeString("Path", subscription.Channel);
            writer.WriteStartElement("Select");
            writer.WriteAttributeString("Path", subscription.Channel);
            writer.WriteString(select);
            writer.WriteEndElement();
            writer.WriteEndElement();
            writer.WriteEndElement();
        }

        StringBuilder output = new();
        XmlWriterSettings settings = new() { Indent = true, IndentChars = "  ", Encoding = new UTF8Encoding(false), NewLineChars = "\n" };
        using (XmlWriter writer = XmlWriter.Create(output, settings))
        {
            writer.WriteStartElement("Subscription", Namespace);
            writer.WriteComment($" Generated by bower wec subscription generate from Bower subscription '{subscription.Id}' (pack {subscription.Pack}). ");
            writer.WriteElementString("SubscriptionId", Namespace, id);
            writer.WriteElementString("SubscriptionType", Namespace, "SourceInitiated");
            writer.WriteElementString("Description", Namespace,
                $"Bower allow-list: channel {subscription.Channel}, event IDs {string.Join(", ", subscription.EventIds)}.");
            writer.WriteElementString("Enabled", Namespace, "true");
            writer.WriteElementString("Uri", Namespace, "http://schemas.microsoft.com/wbem/wsman/1/windows/EventLog");
            writer.WriteElementString("ConfigurationMode", Namespace, options.Mode.ToString());
            writer.WriteStartElement("Delivery", Namespace);
            writer.WriteAttributeString("Mode", "Push");
            if (options.Mode == WecDeliveryMode.Custom)
            {
                writer.WriteStartElement("Batching", Namespace);
                writer.WriteElementString("MaxItems", Namespace, options.MaxItems!.Value.ToString(CultureInfo.InvariantCulture));
                writer.WriteElementString("MaxLatencyTime", Namespace,
                    (options.MaxLatencySeconds!.Value * 1000L).ToString(CultureInfo.InvariantCulture));
                writer.WriteEndElement();
            }

            writer.WriteStartElement("PushSettings", Namespace);
            writer.WriteStartElement("Heartbeat", Namespace);
            writer.WriteAttributeString("Interval", (options.HeartbeatSeconds * 1000L).ToString(CultureInfo.InvariantCulture));
            writer.WriteEndElement();
            writer.WriteEndElement();
            writer.WriteEndElement();
            writer.WriteStartElement("Query", Namespace);
            writer.WriteCData(query.ToString());
            writer.WriteEndElement();
            writer.WriteElementString("ReadExistingEvents", Namespace, options.ReadExistingEvents ? "true" : "false");
            writer.WriteElementString("TransportName", Namespace, "HTTPS");
            // Events, not RenderedText: the collector renders what its subscription asks for
            // (includeMessage), so forwarders send no message strings.
            writer.WriteElementString("ContentFormat", Namespace, "Events");
            writer.WriteStartElement("Locale", Namespace);
            writer.WriteAttributeString("Language", "en-US");
            writer.WriteEndElement();
            writer.WriteElementString("LogFile", Namespace, options.LogFile);
            writer.WriteStartElement("AllowedSourceNonDomainComputers", Namespace);
            if (options.IssuerCaThumbprints is { Count: > 0 } thumbprints)
            {
                writer.WriteStartElement("AllowedIssuerCAList", Namespace);
                foreach (string thumbprint in thumbprints)
                {
                    writer.WriteElementString("IssuerCA", Namespace, thumbprint.ToUpperInvariant());
                }

                writer.WriteEndElement();
            }

            writer.WriteEndElement();
            writer.WriteElementString("AllowedSourceDomainComputers", Namespace,
                options.AllowedSourceDomainComputers ?? DefaultDomainComputers);
            writer.WriteEndElement();
        }

        return output.Append('\n').ToString();
    }

    private static void Validate(WecSubscriptionOptions options)
    {
        if (options.Mode == WecDeliveryMode.Custom)
        {
            if (options.MaxItems is not (>= 1 and <= 10_000) || options.MaxLatencySeconds is not (>= 1 and <= 86_400))
            {
                throw new ArgumentException("Custom delivery needs --max-items 1-10000 and --max-latency-seconds 1-86400.");
            }
        }
        else if (options.MaxItems is not null || options.MaxLatencySeconds is not null)
        {
            throw new ArgumentException("--max-items and --max-latency-seconds apply only to --mode Custom.");
        }

        if (options.HeartbeatSeconds is < 60 or > 86_400)
        {
            throw new ArgumentException("--heartbeat-seconds must be between 60 and 86400.");
        }

        if (options.SubscriptionId is not null && !SubscriptionName().IsMatch(options.SubscriptionId))
        {
            throw new ArgumentException("--subscription-id must be 1-128 letters, digits, '-', '_' or '.'.");
        }

        if (!WindowsEventLogSourceConfigurationLoader.IsName(options.LogFile, allowSlash: true))
        {
            throw new ArgumentException("--log-file must be a channel name of letters, digits, spaces or - _ . / characters.");
        }

        if (options.AllowedSourceDomainComputers is not null && !Sddl().IsMatch(options.AllowedSourceDomainComputers))
        {
            throw new ArgumentException("--allowed-domain-computers must be an SDDL string such as O:NSG:NSD:(A;;GA;;;DC).");
        }

        foreach (string thumbprint in options.IssuerCaThumbprints ?? [])
        {
            if (!Thumbprint().IsMatch(thumbprint))
            {
                throw new ArgumentException("--issuer-ca must be a 40-character SHA-1 certificate thumbprint (hex).");
            }
        }

        if (options.IssuerCaThumbprints is { Count: > 16 })
        {
            throw new ArgumentException("At most 16 --issuer-ca thumbprints.");
        }

    }

    [GeneratedRegex("^[A-Za-z0-9._-]{1,128}$")]
    private static partial Regex SubscriptionName();

    // Owner, group and ACEs only; no XML metacharacters can appear.
    [GeneratedRegex(@"^O:[A-Z0-9-]+G:[A-Z0-9-]+D:(\([A-Za-z0-9;-]+\))+$")]
    private static partial Regex Sddl();

    [GeneratedRegex("^[0-9A-Fa-f]{40}$")]
    private static partial Regex Thumbprint();
}
